package io.github.kingg22.kogot.gradle.test

import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction

/**
 * Generates the two pieces every test compilation needs to be loadable by Godot, into the target's test source set:
 *
 * - `KogotTestRunner`, a `@Godot` node that is the root of the host scene. Its `_ready` runs the Kotlin/Native test
 *   runner (arguments come from Godot's user args, i.e. whatever follows `--`) on the main thread with a live
 *   `SceneTree`, then quits with the runner's exit code. It is not started at extension initialization because the
 *   engine is not fully up there (GDScript cannot compile yet, for one).
 * - the GDExtension entry point that hands the processor's `GeneratedBindings` to Godot.
 */
@CacheableTask
abstract class GenerateTestHarnessTask : DefaultTask() {
    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val dir = outputDir.get().asFile.resolve(HARNESS_PACKAGE.replace('.', '/')).apply { mkdirs() }
        dir.resolve("KogotTestHarness.kt").writeText(SOURCE)
    }

    companion object {
        const val HARNESS_PACKAGE = "io.github.kingg22.kogot.testing"
        const val GENERATED_BINDINGS_PACKAGE = "$HARNESS_PACKAGE.generated"
        const val RUNNER_CLASS = "KogotTestRunner"
        const val ENTRY_SYMBOL = "kogot_test_init"

        private val SOURCE = $$"""
            // Generated by the kogot test Gradle plugin. DO NOT EDIT!
            @file:OptIn(InternalBinding::class, ExperimentalForeignApi::class, ExperimentalNativeApi::class)

            package $$HARNESS_PACKAGE

            import $$GENERATED_BINDINGS_PACKAGE.GeneratedBindings
            import io.github.kingg22.godot.api.annotations.Godot
            import io.github.kingg22.godot.api.builtin.Callable
            import io.github.kingg22.godot.api.core.Node
            import io.github.kingg22.godot.api.singleton.Os
            import io.github.kingg22.godot.internal.binding.BindingProcAddressHolder
            import io.github.kingg22.godot.internal.binding.InternalBinding
            import io.github.kingg22.godot.internal.ffi.GDExtensionBool
            import io.github.kingg22.godot.internal.ffi.GDExtensionClassLibraryPtr
            import io.github.kingg22.godot.internal.ffi.GDExtensionInitialization
            import io.github.kingg22.godot.internal.ffi.GDExtensionInitializationLevel
            import io.github.kingg22.godot.internal.ffi.GDExtensionInterfaceGetProcAddress
            import io.github.kingg22.godot.internal.ffi.TRUE
            import kotlinx.cinterop.COpaquePointer
            import kotlinx.cinterop.CPointer
            import kotlinx.cinterop.ExperimentalForeignApi
            import kotlinx.cinterop.StableRef
            import kotlinx.cinterop.pointed
            import kotlinx.cinterop.staticCFunction
            import kotlin.experimental.ExperimentalNativeApi
            import kotlin.native.internal.test.testLauncherEntryPoint

            @Godot
            class $$RUNNER_CLASS(nativePtr: COpaquePointer) : Node(nativePtr) {
                // Deferred: while `_ready` runs, the root is still "busy setting up children" and tests could not add nodes to it.
                override fun _ready() {
                    Callable { runTests() }.use { it.callDeferred() }
                }

                private fun runTests() {
                    val args = Os.instance.getCmdlineUserArgs().use { packed ->
                        List(packed.size().toInt()) { packed[it.toLong()] }
                    }
                    println("$$BEGIN_MARKER")
                    val code = testLauncherEntryPoint(args.toTypedArray())
                    println("$$RESULT_MARKER$code")
                    getTree().quit(code)
                }
            }

            private val kogotTestCallbacks = StableRef.create(GeneratedBindings())

            @CName("$$ENTRY_SYMBOL")
            fun kogotTestInit(
                pGetProcAddress: GDExtensionInterfaceGetProcAddress,
                pLibrary: GDExtensionClassLibraryPtr,
                initialization: CPointer<GDExtensionInitialization>,
            ): GDExtensionBool {
                BindingProcAddressHolder.initialize(pGetProcAddress, pLibrary)
                val init = initialization.pointed
                init.initialize = staticCFunction { userdata, level -> kogotTestCallbacks.get().initialize(userdata, level) }
                init.deinitialize = staticCFunction { userdata, level -> kogotTestCallbacks.get().deinitialize(userdata, level) }
                init.userdata = null
                init.minimum_initialization_level = GDExtensionInitializationLevel.GDEXTENSION_INITIALIZATION_SCENE
                return GDExtensionBool.TRUE
            }
        """.trimIndent() + "\n"

        /** Printed right before the runner starts; the launcher ignores the engine banner above it. */
        const val BEGIN_MARKER = "KOGOT_RUN_BEGIN"

        /** Printed after the runner; its absence means the engine died before the tests finished. */
        const val RESULT_MARKER = "KOGOT_TEST_RESULT exit="
    }
}
