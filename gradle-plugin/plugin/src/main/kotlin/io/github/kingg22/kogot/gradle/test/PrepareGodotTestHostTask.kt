package io.github.kingg22.kogot.gradle.test

import org.gradle.api.DefaultTask
import org.gradle.api.GradleException
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.provider.ListProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.InputFile
import org.gradle.api.tasks.Internal
import org.gradle.api.tasks.Optional
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction
import java.io.File
import java.util.Properties

/**
 * Lays out everything the test launcher needs, under [hostDir]:
 *
 * - `host/`: a Godot project with no assets, whose main scene is the `KogotTestRunner` node, plus the `.gdextension`
 *   manifest and the test library copied next to it;
 * - `launcher.properties`: how to run it (Godot lookup, timeout, isolation);
 * - `run-godot-tests(.cmd)`: the executable the `<target>Test` task runs instead of the usual test binary. It starts
 *   [GodotTestLauncher] on the JVM that runs Gradle.
 */
@CacheableTask
abstract class PrepareGodotTestHostTask : DefaultTask() {
    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val library: RegularFileProperty

    @get:Input
    abstract val godotMinVersion: Property<String>

    @get:Input
    @get:Optional
    abstract val godotExecutable: Property<String>

    /** Extra arguments of every Godot process: `kogot { godotCliArgs }`, the same ones `runGodot` gets. */
    @get:Input
    abstract val godotCliArgs: ListProperty<String>

    @get:Input
    abstract val timeoutSeconds: Property<Long>

    @get:Input
    abstract val isolation: Property<GodotTestIsolation>

    /** Classpath of the launcher (this plugin and the Kotlin stdlib). Not a file input: it is the plugin itself. */
    @get:Input
    abstract val launcherClasspath: Property<String>

    @get:Input
    abstract val javaExecutable: Property<String>

    @get:OutputDirectory
    abstract val hostDir: DirectoryProperty

    /** The script `<target>Test` runs. */
    @get:Internal
    val script: File
        get() = hostDir.get().asFile.resolve(scriptName())

    @TaskAction
    fun prepare() {
        val root = hostDir.get().asFile.apply { mkdirs() }

        val host = File(root, "host").apply { mkdirs() }

        val lib = library.get().asFile

        val bin = File(host, "bin").apply { mkdirs() }
        lib.copyTo(File(bin, lib.name), overwrite = true)

        File(host, "project.godot").writeText(
            """
            ; Generated by the kogot test Gradle plugin. DO NOT EDIT!
            config_version=5

            [application]

            config/name="kogot-godot-tests"
            run/main_scene="res://main.tscn"
            config/features=PackedStringArray("${godotMinVersion.get().substringBeforeLast('.')}")
            """.trimIndent() + "\n",
        )

        File(host, "main.tscn").writeText(
            "[gd_scene format=3]\n\n[node name=\"Main\" type=\"${GenerateTestHarnessTask.RUNNER_CLASS}\"]\n",
        )

        val feature = when {
            lib.extension == "dylib" -> "macos"
            lib.extension == "dll" -> "windows"
            else -> "linux"
        }

        val arch = if (feature == "macos") "" else ".x86_64"

        File(host, "kogot_tests.gdextension").writeText(
            """
            [configuration]
            entry_symbol = "${GenerateTestHarnessTask.ENTRY_SYMBOL}"
            compatibility_minimum = "${godotMinVersion.get()}"

            [libraries]
            $feature.debug$arch = "res://bin/${lib.name}"
            """.trimIndent() + "\n",
        )

        val config = File(root, "launcher.properties")

        Properties().apply {
            setProperty("host", host.absolutePath)
            setProperty(
                "godot.executable",
                godotExecutable.orNull ?: throw GradleException(
                    "Godot executable not found. Set kogot.godotExecutable (gradle.properties), GODOT_BIN, " +
                        "or put 'godot' on PATH",
                ),
            )
            setProperty("godot.args", godotCliArgs.get().joinToString("\n"))
            setProperty("timeout.seconds", timeoutSeconds.get().toString())
            setProperty("isolation", isolation.get().name)
        }.also { props -> config.outputStream().use { props.store(it, "kogot test launcher") } }

        val java = javaExecutable.get()
        val main = GodotTestLauncher::class.java.name
        val launcher = script

        if (launcher.name.endsWith(".cmd")) {
            launcher.writeText(
                "@echo off\r\n\"$java\" -cp \"${launcherClasspath.get()}\" $main \"${config.absolutePath}\" %*\r\n",
            )
        } else {
            launcher.writeText(
                "#!/bin/sh\nexec \"$java\" -cp \"${launcherClasspath.get()}\" $main \"${config.absolutePath}\" \"$@\"\n",
            )
            launcher.setExecutable(true)
        }
    }

    private fun scriptName() = if (System.getProperty("os.name").lowercase().contains("win")) {
        "run-godot-tests.cmd"
    } else {
        "run-godot-tests"
    }
}
