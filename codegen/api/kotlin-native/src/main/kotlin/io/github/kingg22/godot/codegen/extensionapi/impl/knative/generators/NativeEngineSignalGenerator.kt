package io.github.kingg22.godot.codegen.extensionapi.impl.knative.generators

import com.squareup.kotlinpoet.CodeBlock
import com.squareup.kotlinpoet.LambdaTypeName
import com.squareup.kotlinpoet.MemberName
import com.squareup.kotlinpoet.ParameterSpec
import com.squareup.kotlinpoet.ParameterizedTypeName.Companion.parameterizedBy
import com.squareup.kotlinpoet.PropertySpec
import com.squareup.kotlinpoet.STRING
import com.squareup.kotlinpoet.TypeName
import com.squareup.kotlinpoet.UNIT
import io.github.kingg22.godot.codegen.extensionapi.Context
import io.github.kingg22.godot.codegen.extensionapi.TypeResolver
import io.github.kingg22.godot.codegen.extensionapi.resolver.addKdocIfPresent
import io.github.kingg22.godot.codegen.extensionapi.resolver.experimentalApiAnnotation
import io.github.kingg22.godot.codegen.impl.safeIdentifier
import io.github.kingg22.godot.codegen.models.extensionapi.EngineClass
import io.github.kingg22.godot.codegen.models.extensionapi.MethodArg
import io.github.kingg22.godot.codegen.models.extensionapi.domain.ResolvedEngineClass
import io.github.kingg22.godot.codegen.utils.withExceptionContext

/**
 * Exposes the signals declared in `extension_api.json` as properties of the engine class, like Godot does:
 * ```
 * public val childEnteredTree: TypedSignal<(node: Node) -> Unit>
 *     by signal<(node: Node) -> Unit>("child_entered_tree")
 * ```
 * Only the signals the class declares itself are generated: subclasses inherit the rest through Kotlin inheritance.
 *
 * The `signal` delegate keeps one `TypedSignal` per instance and property. These signals already exist in Godot, so
 * nothing is registered (no `@RegisterSignal`). Argument names and types come from the JSON, which is what the typed
 * `connect` and `emit` (generated by the `SIGNAL` runner) check at compile time.
 */
class NativeEngineSignalGenerator(private val typeResolver: TypeResolver) {

    context(ctx: Context)
    fun buildProperties(cls: ResolvedEngineClass): List<PropertySpec> {
        if (cls.signals.isEmpty()) return emptyList()

        val typedSignal = ctx.classNameForOrDefault("TypedSignal")
        val delegate = ctx.memberNameForOrDefault("signal")

        return cls.signals.map { signal ->
            withExceptionContext({ "Generating signal '${signal.name}' of '${cls.name}'" }) {
                val handler = handlerType(signal)

                PropertySpec
                    .builder(safeIdentifier(signal.name), typedSignal.parameterizedBy(handler))
                    .addKdocIfPresent(signal)
                    .experimentalApiAnnotation(cls.name, signal.name)
                    .delegate(delegateCall(delegate, handler, signal))
                    .build()
            }
        }
    }

    /**
     * `signal("name")` for no arguments, `signal<(a: A) -> Unit>("name")` otherwise: the explicit type argument keeps
     * the generic overload from being ambiguous with the `() -> Unit` one.
     */
    private fun delegateCall(delegate: MemberName, handler: LambdaTypeName, signal: EngineClass.Signal) =
        CodeBlock.of("%M<%T>(%S)", delegate, handler, signal.name)

    /** `(name: Type, ...) -> Unit`: the parameter names are what `connect` handlers and the compiler plugin show. */
    context(ctx: Context)
    private fun handlerType(signal: EngineClass.Signal) = LambdaTypeName.get(
        parameters = signal.arguments.map { ParameterSpec.builder(safeIdentifier(it.name), argumentType(it)).build() },
        returnType = UNIT,
    )

    /** `String` is a Kotlin `String` (the Variant conversion handles it); everything else follows the API resolver. */
    context(ctx: Context)
    private fun argumentType(arg: MethodArg): TypeName = if (arg.type == "String") STRING else typeResolver.resolve(arg)
}
