package io.github.kingg22.kogot.processor.generators.kotlin

import io.github.kingg22.kogot.processor.model.AnnotationInfo
import io.github.kingg22.kogot.processor.model.ClassInfo
import io.github.kingg22.kogot.processor.model.FunctionInfo
import io.github.kingg22.kogot.processor.model.GodotPrimitives
import io.github.kingg22.kogot.processor.model.ParameterInfo
import io.github.kingg22.kogot.processor.model.PropertyInfo
import io.github.kingg22.kogot.processor.model.TypeInfo
import org.junit.jupiter.api.Assertions.assertFalse
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.BeforeEach
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.io.TempDir
import java.io.File

/**
 * Covers the `ScriptFileRegistry` generated by [GodotBindingGenerator], which maps a source file to
 * the single `@Godot` class it declares (see issue #42 — Kotlin as a Godot script language).
 */
class GodotBindingGeneratorScriptRegistryTest {
    private val generator = GodotBindingGenerator()

    /** A Godot project (`project.godot` at its root) whose sources live under `src/`. */
    @TempDir
    lateinit var project: File

    @BeforeEach
    fun createProject() {
        File(project, "project.godot").writeText("config_version=5\n")
        File(project, "src").mkdirs()
    }

    private fun src(name: String): String = File(project, "src/$name").path

    private val exportAnnotation =
        AnnotationInfo(qualifiedName = "io.github.kingg22.godot.api.annotations.Export", shortName = "Export")
    private val exportMethodAnnotation = AnnotationInfo(
        qualifiedName = "io.github.kingg22.godot.api.annotations.ExportMethod",
        shortName = "ExportMethod",
    )

    private fun godotClass(
        qualifiedName: String,
        filePath: String,
        properties: List<PropertyInfo> = emptyList(),
        functions: List<FunctionInfo> = emptyList(),
    ): ClassInfo = ClassInfo(
        qualifiedName = qualifiedName,
        shortName = qualifiedName.substringAfterLast('.'),
        packageName = qualifiedName.substringBeforeLast('.'),
        supertypes = listOf(TypeInfo(qualifiedName = "io.github.kingg22.godot.api.core.Node", shortName = "Node")),
        annotations = listOf(
            AnnotationInfo(qualifiedName = "io.github.kingg22.godot.api.annotations.Godot", shortName = "Godot"),
        ),
        properties = properties,
        functions = functions,
        filePath = filePath,
    )

    private fun GenerationResult.registryContent(): String =
        files.single { it.relativePath.endsWith("ScriptFileRegistry.kt") }.content

    @Test
    fun `when a file declares exactly one Godot class, then it is addressable in the registry`() {
        val result = generator.generate(listOf(godotClass("io.github.kingg22.game.Player", src("Player.kt"))))

        val content = result.registryContent()
        assertTrue(content.contains("\"res://src/Player.kt\" to"))
        assertTrue(content.contains("KotlinScriptRegistry.Entry("))
        assertTrue(content.contains("\"Player\","))
        assertTrue(content.contains("\"Node\","))
        assertTrue(content.contains("properties = emptyList(),"))
        assertTrue(content.contains("methods = emptyList(),"))
    }

    @Test
    fun `when a file declares two Godot classes, then neither is addressable in the registry`() {
        val classes = listOf(
            godotClass("io.github.kingg22.game.Foo", src("Multi.kt")),
            godotClass("io.github.kingg22.game.Bar", src("Multi.kt")),
        )

        val content = generator.generate(classes).registryContent()

        assertFalse(content.contains("Multi.kt"))
    }

    @Test
    fun `when multiple files each declare one Godot class, then all are addressable`() {
        val classes = listOf(
            godotClass("io.github.kingg22.game.Foo", src("Foo.kt")),
            godotClass("io.github.kingg22.game.Bar", src("Bar.kt")),
        )

        val content = generator.generate(classes).registryContent()

        assertTrue(content.contains("\"res://src/Foo.kt\" to"))
        assertTrue(content.contains("\"Foo\","))
        assertTrue(content.contains("\"res://src/Bar.kt\" to"))
        assertTrue(content.contains("\"Bar\","))
    }

    @Test
    fun `when a class has exported members, then the entry references its binding trampolines`() {
        val intType = TypeInfo(qualifiedName = GodotPrimitives.INT, shortName = "Int")
        val classInfo = godotClass(
            "io.github.kingg22.game.Player",
            src("Player.kt"),
            properties = listOf(
                PropertyInfo(
                    name = "health",
                    type = intType,
                    isMutable = true,
                    annotations = listOf(exportAnnotation),
                ),
                PropertyInfo(
                    name = "readOnlyStat",
                    type = intType,
                    isMutable = false,
                    annotations = listOf(exportAnnotation),
                ),
            ),
            functions = listOf(
                FunctionInfo(
                    name = "heal",
                    returnType = null,
                    parameters = listOf(ParameterInfo(name = "amount", type = intType)),
                    annotations = listOf(exportMethodAnnotation),
                ),
            ),
        )

        val content = generator.generate(listOf(classInfo)).registryContent()

        assertTrue(
            content.contains(
                "ScriptPropertyDescriptor(\"health\", Variant.Type.INT, " +
                    "Player_Binding._godot_get_health, Player_Binding._godot_set_health)",
            ),
        )
        assertTrue(
            content.contains(
                "ScriptPropertyDescriptor(\"readOnlyStat\", Variant.Type.INT, " +
                    "Player_Binding._godot_get_readOnlyStat, null)",
            ),
        )
        assertTrue(content.contains("ScriptMethodDescriptor(\"heal\", 1, Player_Binding._godot_call_heal)"))
    }

    // ── Keys: res:// paths, not build-machine paths (#217) ──────────────────────────

    @Test
    fun `the key is the res path of the file, never its absolute path`() {
        val content = generator.generate(listOf(godotClass("game.Player", src("Player.kt")))).registryContent()

        assertTrue(content.contains("\"res://src/Player.kt\" to"), content)
        assertFalse(content.contains(project.path), content)
    }

    @Test
    fun `the same project built in two directories gives the same registry`(@TempDir other: File) {
        File(other, "project.godot").writeText("config_version=5\n")
        val here = generator.generate(listOf(godotClass("game.Player", src("Player.kt")))).registryContent()
        val there = generator.generate(listOf(godotClass("game.Player", File(other, "src/Player.kt").path)))
            .registryContent()

        assertTrue(here == there, "registry differs between build directories:\n$here\n---\n$there")
    }

    @Test
    fun `the nearest project godot is the res root`() {
        val nested = File(project, "addons/plugin").apply { mkdirs() }
        File(nested, "project.godot").writeText("config_version=5\n")

        assertTrue(godotResPath(File(nested, "Tool.kt").path) == "res://Tool.kt")
        assertTrue(godotResPath(src("deep/dir/Thing.kt")) == "res://src/deep/dir/Thing.kt")
    }

    @Test
    fun `a file outside any Godot project is not addressable`(@TempDir outside: File) {
        val content = generator.generate(listOf(godotClass("game.Loose", File(outside, "Loose.kt").path)))
            .registryContent()

        assertFalse(content.contains("Loose"), content)
        assertTrue(godotResPath("") == null)
    }
}
